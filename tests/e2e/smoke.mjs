// Quick visual smoke test: two separate browser contexts join one room.
import { chromium } from 'playwright-core';
const URL = process.env.URL || 'http://localhost:8090/';
const OUT = process.env.OUT || '/tmp/claude-0/shots';
import fs from 'node:fs';
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--autoplay-policy=no-user-gesture-required'] });
const mk = async () => { const c = await browser.newContext({ viewport: { width: 1280, height: 720 } }); const p = await c.newPage(); p.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text()); }); p.on('pageerror', (e) => console.log('[pageerror]', e.message)); return p; };
const a = await mk();
const b = await mk();
await a.goto(URL);
await a.waitForTimeout(800);
await a.screenshot({ path: `${OUT}/01-title.png` });
await a.click('text=Tạo phòng mới');
await a.fill('input[type=text]', 'Mai');
await a.screenshot({ path: `${OUT}/02-create.png` });
await a.click('text=Tạo phòng ▶');
await a.waitForSelector('.code');
const code = (await a.textContent('.code')).trim();
console.log('room', code);
await b.goto(URL + '?room=' + code);
await b.waitForTimeout(500);
await b.fill('input[placeholder^="Tên"]', 'Khoa');
await b.click('text=Vào phòng ▶');
await a.waitForTimeout(800);
await a.screenshot({ path: `${OUT}/03-wait.png` });
await a.click('text=Bắt đầu ▶');
await a.waitForTimeout(2500);
await a.screenshot({ path: `${OUT}/04-intro-a.png` });
await b.screenshot({ path: `${OUT}/04-intro-b.png` });
await browser.close();
